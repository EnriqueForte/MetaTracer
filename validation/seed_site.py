"""Seed-site generator for real-environment validation (post-MVP Phase 0).

Writes the synthetic fixture files from the test-suite factory — same bytes,
same planted leaks — plus a ``ground_truth.json`` describing exactly what a
scan of the site must report. Upload the output directory to a domain **you
own**, scan it with the CLI and score the run with ``validation.measure``::

    .venv\\Scripts\\python.exe -m validation.seed_site --target https://validation.example.com
    # upload validation/site/ to the domain, then:
    .venv\\Scripts\\python.exe -m metatracer scan https://validation.example.com
    .venv\\Scripts\\python.exe -m validation.measure --report reports\\<file>.json ^
        --ground-truth validation\\site\\ground_truth.json --min-precision 1.0 --min-recall 1.0

No network access and no third-party site is involved: this script only
writes local files built by :mod:`tests.fixtures.generate_test_fixtures`
(synthetic domain ``acme-corp.internal``, synthetic users and paths).
"""

import argparse
from pathlib import Path

from metatracer.db.models import Severity
from tests.fixtures.generate_test_fixtures import (
    FIXTURE_SPECS,
    GPS_LATITUDE,
    GPS_LONGITUDE,
    TEST_EMAIL,
)
from tests.fixtures.generate_test_fixtures import main as write_fixture_files
from validation.ground_truth import ExpectedFinding, GroundTruth, GroundTruthAsset

DEFAULT_OUTPUT_DIR = Path(__file__).parent / "site"
DEFAULT_TARGET = "https://validation.example.com"

# Per-fixture evidence substrings and calibrated severities, keyed by
# FixtureSpec.name — two fixtures may share a finding type with different
# expectations (the strong "debug" vs the weak "weak-keyword"). Substrings are
# guaranteed to appear in the evidence snippet of each detector's finding for
# the planted values (see the constants in tests/fixtures/generate_test_fixtures.py).
_EVIDENCE_BY_SPEC: dict[str, list[str]] = {
    "gps": [str(GPS_LATITUDE), str(GPS_LONGITUDE)],
    "email": [TEST_EMAIL],
    "internal-path": ["dev_admin", "ConfidentialApp"],
    "software": ["Apache FOP", "2.4"],
    "debug": ["TODO", "JIRA-4412"],
    "weak-keyword": ["INTERNAL"],
}

# Calibrated severities per the TASK-03 rubric, confirmed by operator triage on
# 2026-09-06 (first real scan, run adb6e8d0): GPS without context = high; path
# with username = high; corporate email = medium; ticket/staging comment
# without a secret value = medium; bare name+version = low; isolated weak
# keyword = info (rubric: "generic or weak evidence").
_SEVERITY_BY_SPEC: dict[str, Severity] = {
    "gps": Severity.high,
    "email": Severity.medium,
    "internal-path": Severity.high,
    "software": Severity.low,
    "debug": Severity.medium,
    "weak-keyword": Severity.info,
}


def build_ground_truth(target: str) -> GroundTruth:
    """Ground truth derived from the fixture specs, always in sync with the bytes.

    ``expected_severity`` carries the calibrated values from
    ``_SEVERITY_BY_SPEC`` (rubric + operator triage, 2026-09-06), so
    ``validation.measure`` scores detection, evidence AND severity calibration.
    """
    assets = []
    for spec in FIXTURE_SPECS:
        expectations = [
            ExpectedFinding(
                type=finding_type,
                evidence_contains=list(_EVIDENCE_BY_SPEC.get(spec.name, [])),
                expected_severity=_SEVERITY_BY_SPEC.get(spec.name),
            )
            for finding_type in sorted(spec.expected_types, key=lambda t: t.value)
        ]
        assets.append(GroundTruthAsset(url_path=f"/{spec.filename}", expect_findings=expectations))
    return GroundTruth(
        target=target,
        complete=True,
        notes=(
            "Synthetic seed site generated by validation.seed_site; every value is "
            "synthetic (acme-corp.internal). Severities calibrated per the TASK-03 "
            "rubric and confirmed by operator triage on 2026-09-06."
        ),
        assets=assets,
    )


def main() -> list[Path]:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=DEFAULT_OUTPUT_DIR,
        help=f"where to write the site (default: {DEFAULT_OUTPUT_DIR})",
    )
    parser.add_argument(
        "--target",
        default=DEFAULT_TARGET,
        help="public base URL the files will be served from (recorded in ground_truth.json)",
    )
    args = parser.parse_args()

    written = write_fixture_files(args.output_dir)
    ground_truth = build_ground_truth(args.target)
    gt_path = args.output_dir / "ground_truth.json"
    gt_path.write_text(
        ground_truth.model_dump_json(indent=2) + "\n",
        encoding="utf-8",
    )
    written.append(gt_path)
    for path in written:
        print(f"wrote {path}")
    print(
        "\nUpload everything EXCEPT ground_truth.json to your domain "
        f"({args.target}), then scan it and run validation.measure."
    )
    return written


if __name__ == "__main__":
    main()
